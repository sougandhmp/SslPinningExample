#!/usr/bin/env bash
# Generates a test CA plus three server keys/certs, then writes the pins into the app.
#
#   key A = current production key   (pinned)
#   key B = backup / next key        (pinned, used for rotation)
#   key C = "rogue" key              (NOT pinned, but signed by the same trusted CA)
#
# Usage: ./scripts/gen_certs.sh [HOST]
#   HOST defaults to 10.0.2.2 (the Android emulator's alias for your computer).
#   For a physical device, pass your computer's LAN IP, e.g. ./scripts/gen_certs.sh 192.168.1.20
set -euo pipefail

HOST="${1:-10.0.2.2}"
PORT="${PORT:-8443}"
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$SCRIPT_DIR/.."
OUT="$SCRIPT_DIR/certs"
RES="$ROOT/app/src/main/res"

mkdir -p "$OUT"
cd "$OUT"
rm -f ./*.pem ./*.csr ./*.srl ./*.cnf ./*.ext

if [[ "$HOST" =~ ^[0-9.]+$ ]]; then SAN_HOST="IP:$HOST"; else SAN_HOST="DNS:$HOST"; fi

cat > ca.cnf <<EOF
[req]
distinguished_name = dn
x509_extensions    = v3_ca
prompt             = no
[dn]
CN = SSL Pinning Test CA
[v3_ca]
basicConstraints     = critical,CA:TRUE
keyUsage             = critical,keyCertSign,cRLSign
subjectKeyIdentifier = hash
EOF

cat > leaf.ext <<EOF
basicConstraints = CA:FALSE
keyUsage         = critical,digitalSignature,keyEncipherment
extendedKeyUsage = serverAuth
subjectAltName   = $SAN_HOST,DNS:localhost,IP:127.0.0.1
EOF

echo "==> Creating test CA"
openssl req -x509 -newkey rsa:2048 -nodes -keyout ca_key.pem -out ca.pem -days 825 -config ca.cnf 2>/dev/null

pin_of() { # SPKI SHA-256 pin of a private key, base64
  openssl pkey -in "$1" -pubout -outform der | openssl dgst -sha256 -binary | openssl enc -base64
}

for k in a b c; do
  echo "==> Creating key/cert $k"
  openssl genrsa -out "key_$k.pem" 2048 2>/dev/null
  openssl req -new -key "key_$k.pem" -subj "/CN=$HOST" -out "$k.csr"
  openssl x509 -req -in "$k.csr" -CA ca.pem -CAkey ca_key.pem -CAcreateserial \
    -days 397 -extfile leaf.ext -out "cert_$k.pem" 2>/dev/null
done

PIN_A="$(pin_of key_a.pem)"
PIN_B="$(pin_of key_b.pem)"
PIN_C="$(pin_of key_c.pem)"
EXPIRY="$(date -u -d '+1 year' +%F 2>/dev/null || date -u -v+1y +%F)"

echo "==> Writing app config"
cp ca.pem "$RES/raw/test_ca.pem"

cat > "$ROOT/pins.properties" <<EOF
# Generated by scripts/gen_certs.sh. Do not edit by hand.
testHost=$HOST
testPort=$PORT
pinA=sha256/$PIN_A
pinB=sha256/$PIN_B
pinC=sha256/$PIN_C
EOF

cat > "$RES/xml/network_security_config.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen_certs.sh. Do not edit by hand. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>

    <domain-config cleartextTrafficPermitted="false">
        <domain includeSubdomains="false">$HOST</domain>
        <!-- Trust the local test CA for this host only. -->
        <trust-anchors>
            <certificates src="@raw/test_ca" />
        </trust-anchors>
        <!-- Current key (A) + backup key (B). Key C is deliberately NOT pinned.
             After the expiration date, Android stops enforcing these pins (fail-open). -->
        <pin-set expiration="$EXPIRY">
            <pin digest="SHA-256">$PIN_A</pin>
            <pin digest="SHA-256">$PIN_B</pin>
        </pin-set>
    </domain-config>
</network-security-config>
EOF

rm -f ./*.csr ./*.srl ./*.cnf ./*.ext
echo
echo "Host:  $HOST:$PORT"
echo "Pin A: sha256/$PIN_A   (current, pinned)"
echo "Pin B: sha256/$PIN_B   (backup, pinned)"
echo "Pin C: sha256/$PIN_C   (rogue, not pinned)"
echo "NSC pin-set expires: $EXPIRY"
echo
echo "Rebuild the app after regenerating certs."
